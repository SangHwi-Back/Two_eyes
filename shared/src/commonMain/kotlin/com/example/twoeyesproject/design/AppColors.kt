package com.example.twoeyesproject.design

/**
 * Two Eyes 앱 전체에서 공유하는 색상 디자인 토큰.
 *
 * ## 사용 원칙
 * - **직접 하드코딩 금지**: 뷰 파일에 `#4F8EF7` 같은 리터럴을 쓰지 말고 여기서 참조하세요.
 * - **레이아웃·사이즈는 각 플랫폼 몫**: 이 파일은 색상 값만 정의합니다.
 *   Android는 `composeApp`, iOS는 `iosApp` 에서 이 값을 가져다 쓰세요.
 * - **다크 모드 기준**: 모든 색상은 다크 테마 기준으로 정의되어 있습니다.
 *   라이트 테마가 필요하면 별도 `AppColorsLight` 오브젝트를 만들어 확장하세요.
 *
 * ## 팔레트 개요
 * 배경은 순수한 검정 대신 **딥 네이비 계열**을 사용합니다.
 * 이미지 작업 앱 특성상 사진이 주인공이며, 네이비 배경은 사진 색감과
 * 자연스럽게 어우러지면서도 True Black 보다 눈의 피로가 적습니다.
 * Primary 는 **소프트 블루**, Secondary 는 **소프트 바이올렛**으로
 * "두 눈", "두 이미지가 합쳐지는" 앱 컨셉을 색상으로 표현합니다.
 */
object AppColors {

    // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
    // MARK: - Background
    // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

    /**
     * 앱 전체의 최하단 배경색.
     *
     * 딥 네이비에 가까운 거의 검정. 사진을 전면에 부각시키면서
     * OLED 디스플레이에서 배터리 효율도 어느 정도 챙길 수 있습니다.
     * - 사용처: 화면 배경, NavigationStack 배경, 전체 루트 뷰 배경
     */
    const val Background = 0xFF0D0F14L

    /**
     * 카드, 모달 시트, 셀 등 배경보다 한 단계 위에 있는 UI 요소의 색.
     *
     * 배경과 충분한 대비를 주면서도 눈에 튀지 않도록 미세한 네이비 틴트가 들어 있습니다.
     * - 사용처: 이미지 슬롯 카드, 하단 버튼 컨테이너, 리스트 셀 배경
     */
    const val Surface = 0xFF1A1D26L

    /**
     * Surface 보다 한 단계 더 밝은 중간 레이어.
     *
     * 입력 필드, 비활성 슬롯, 선택 안 된 썸네일 배경 등
     * Surface 위에 올라가는 요소에 사용합니다.
     * - 사용처: 이미지 미선택 슬롯, 세컨더리 버튼 배경, 칩 배경
     */
    const val Surface2 = 0xFF252836L

    /**
     * 섹션 간 구분선 또는 얇은 테두리 색.
     *
     * 시각적 노이즈를 최소화하면서 영역을 나눕니다.
     * - 사용처: `Divider`, 카드 테두리, 리스트 구분선
     */
    const val Divider = 0xFF2C2F3DL

    // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
    // MARK: - Brand
    // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

    /**
     * 앱의 핵심 액션에 사용하는 메인 색상. 소프트 블루.
     *
     * iOS 시스템 블루(`#0A84FF`)보다 밝기를 살짝 낮춰
     * 다크 배경 위에서 눈부심 없이 선명하게 보입니다.
     * - 사용처: 주요 버튼(확인, 저장, 머징 시작), 선택된 슬롯 테두리, 탭 인디케이터
     */
    const val Primary = 0xFF4F8EF7L

    /**
     * 보조 액션 또는 강조 요소에 사용하는 색상. 소프트 바이올렛.
     *
     * 블루 계열 Primary 와 자연스럽게 그라데이션을 이루며,
     * "두 요소가 혼합되는" 앱 아이덴티티를 시각적으로 표현합니다.
     * - 사용처: 선택됨 뱃지, 하이라이트 인디케이터, 진행 중 상태 칩
     */
    const val Secondary = 0xFF7B61FFL

    /**
     * 포인트 액션에 사용하는 따뜻한 앰버 색상.
     *
     * 쿨톤 메인 팔레트에 온기를 더합니다.
     * 너무 자주 쓰면 강조 효과가 희석되므로 한 화면에 1~2곳만 사용하세요.
     * - 사용처: Swap 버튼, 특별 액션 버튼, 알림 아이콘 틴트
     */
    const val Accent = 0xFFF5A623L

    // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
    // MARK: - Text
    // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

    /**
     * 제목, 본문 등 가장 읽기 쉬워야 하는 텍스트 색.
     *
     * 순수 흰색(`#FFFFFF`) 대신 아주 살짝 차가운 오프화이트를 사용해
     * 장시간 사용 시 눈의 피로를 줄입니다.
     * - 사용처: 화면 제목, 버튼 레이블, 리스트 셀 주요 텍스트
     */
    const val TextPrimary = 0xFFF0F1F5L

    /**
     * 설명, 캡션, 보조 정보 텍스트 색.
     *
     * Primary 대비 읽기 우선순위가 낮은 텍스트에 사용합니다.
     * - 사용처: 서브타이틀, 날짜·시간 표시, 힌트 텍스트
     */
    const val TextSecondary = 0xFF8B8FA8L

    /**
     * 비활성 상태의 텍스트 또는 아이콘 색.
     *
     * 사용자가 현재 상호작용할 수 없는 요소임을 나타냅니다.
     * - 사용처: 비활성 버튼 레이블, placeholder 텍스트, disabled 아이콘
     */
    const val TextDisabled = 0xFF4A4D5EL

    // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
    // MARK: - Status
    // ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

    /**
     * 성공·완료 상태를 나타내는 색상. 소프트 그린.
     *
     * - 사용처: 이미지 저장 완료 메시지, 체크마크 아이콘, 성공 토스트
     */
    const val Success = 0xFF34C770L

    /**
     * 오류·실패 상태를 나타내는 색상. 소프트 레드.
     *
     * - 사용처: 저장 실패 알럿, 입력 오류 표시, 에러 토스트
     */
    const val Error = 0xFFFF5A5AL
}
